def export_all(spec: dict, n8n_workflow: dict, out: Path) -> dict[str, Path]:
    """Every platform's file, next to n8n_workflow.json (written by build.py)."""
    p = dict(plan(spec), _n8n=n8n_workflow)
    files = {}
    for t in TARGETS.values():
        if t.id == "n8n":
            continue
        path = out / t.file
        doc = t.render(p)
        path.write_text(json.dumps(t.export(doc) if t.export else doc, indent=2, ensure_ascii=False),
                        encoding="utf-8")
        files[f"{t.name} file"] = path
    return files


def values(target: Target) -> dict:
    """The target's settings from the user's environment (where the app's Build dialog saves them)."""
    from .app import saved_key

    v = {s.env: saved_key(s.env) or os.environ.get(s.env, "") for s in target.settings}
    missing = [s.label for s in target.settings if not s.optional and not v[s.env] and not s.default]
    if missing:
        raise SystemExit(f"{target.name}: enter {', '.join(missing)} first (Build automation > Create it in).")
    for s in target.settings:
        v[s.env] = v[s.env] or s.default
    return v


def create(target_id: str, spec: dict, n8n_workflow: dict, settings: dict | None = None) -> str:
    target = TARGETS[target_id]
    p = dict(plan(spec), _n8n=n8n_workflow)
    v = settings if settings is not None else values(target)
    v = dict(v, _slug=p["slug"])
    return target.create(target.render(p), v)


def _call(service: str, method: str, url: str, headers: dict | None = None, body=None, timeout: int = 30):
    data = None if body is None else json.dumps(body, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(url, data=data, method=method, headers={
        "Accept": "application/json", **({"Content-Type": "application/json"} if data else {}), **(headers or {})})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as resp:
            raw = resp.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")[:300]
        hint = " Check the key or token." if exc.code in (401, 403) else ""
        raise SystemExit(f"{service} refused it ({exc.code}).{hint} {detail}".strip()) from None
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise SystemExit(f"Can't reach {service} at {url.split('?')[0]}: {getattr(exc, 'reason', exc)}") from None
    if not raw.strip():
        return {}
    try:
        data = json.loads(raw)
    except ValueError:
        return {"text": raw}
    return data if isinstance(data, dict) else {"result": data}
