"""Create the automation in the tool the business runs workflows in, with one click.

Every target gets the plan the n8n workflow follows (on a schedule or a new email: read the PDF fields, add the
row, send to the portal, move the email) in its own format. The files are written next to n8n_workflow.json, so
each can also be imported by hand. Creating one through the platform's API leaves it switched off, for a person
to add credentials, replace the warning-sign values, test and switch on.

Which platforms can create a workflow from an API at all (checked against their API docs, October 2026):
  yes, with a pasted key    n8n, Node-RED, Windmill, Make (Core plan and up), Activepieces (paid editions)
  yes, with a Microsoft or  Power Automate cloud flows (Dataverse), Azure Logic Apps, Google Apps Script,
  Google sign-in            Workato (some plans)
  no                        Zapier (partners only), Power Automate Desktop, Pipedream (copies templates only),
                            UiPath and Automation Anywhere (import packages built in their own studios)
"""
