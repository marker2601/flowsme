def _chain(actions: dict, name: str, action: dict) -> None:
    action["runAfter"] = {list(actions)[-1]: ["Succeeded"]} if actions else {}
    actions[name] = action


def _wdl_value(c: dict, fields: str) -> str:
    if "pdf" in c:
        return f"@{{{fields}?['{c['pdf']}']}}" + (f" {WARN}" if "warn" in c else "")
    return f"{WARN} {c['warn']}"


def _pdf_compose(p: dict, how: str) -> dict:
    return {"type": "Compose", "inputs": {label: f"{WARN} {how}" for label in p["labels"]}}


def power_automate_flow(p: dict) -> dict:
    """A cloud flow with the Office 365 Outlook and Excel Online connectors (connections are picked on import)."""
    def connector(api: str, operation: str, parameters: dict) -> dict:
        return {"type": "OpenApiConnection",
                "inputs": {"host": {"apiId": f"/providers/Microsoft.PowerApps/apis/{api}", "connectionName": api,
                                    "operationId": operation},
                           "parameters": parameters, "authentication": "@parameters('$authentication')"}}

    if p["emails"]:
        triggers = {"When_a_new_email_arrives_(V3)": {
            "type": "OpenApiConnectionNotification", "splitOn": "@triggerOutputs()?['body/value']",
            "inputs": {"host": {"apiId": "/providers/Microsoft.PowerApps/apis/shared_office365",
                                "connectionName": "shared_office365", "operationId": "OnNewEmailV3"},
                       "parameters": {"folderPath": "Inbox", "importance": "Any", "fetchOnlyWithAttachment": True,
                                      "includeAttachments": True},
                       "authentication": "@parameters('$authentication')"}}}
    else:
        triggers = {"Every_15_minutes": {"type": "Recurrence", "recurrence": {"frequency": "Minute", "interval": 15}}}
    actions: dict = {}
    if p["labels"]:
        _chain(actions, "Read_the_PDF_fields", _pdf_compose(
            p, "AI Builder: Extract information from invoices (premium), or Azure Document Intelligence"))
    fields = "outputs('Read_the_PDF_fields')"
    if p["sheet"]:
        sheet = p["sheet"]
        params = {"source": "me", "drive": f"{WARN} OneDrive", "file": f"{WARN} /folder/{sheet['workbook']}",
                  "table": f"{WARN} Table1"}
        params.update({f"item/{c['name']}": _wdl_value(c, fields) for c in sheet["columns"]})
        _chain(actions, "Add_a_row_into_a_table", connector("shared_excelonlinebusiness", "AddRowV2", params))
    if p["web"]:
        web = p["web"]
        _chain(actions, f"Send_to_{_slug(web['site'])}", {"type": "Http", "inputs": {
            "method": "POST", "uri": web["url"], "body": {c["name"]: _wdl_value(c, fields) for c in web["fields"]}}})
    if p["move_to"]:
        _chain(actions, "Move_email_(V2)", connector("shared_office365", "MoveV2", {
            "messageId": "@triggerOutputs()?['body/id']", "folderPath": f"{WARN} id of the {p['move_to']} folder"}))
    definition = {"$schema": "https://schema.management.azure.com/providers/Microsoft.Logic/schemas/2016-06-01/"
                             "workflowdefinition.json#", "contentVersion": "1.0.0.0",
                  "parameters": {"$connections": {"defaultValue": {}, "type": "Object"},
                                 "$authentication": {"defaultValue": {}, "type": "SecureObject"}},
                  "triggers": triggers, "actions": actions}
    refs = {api: {"runtimeSource": "embedded", "connection": {}, "api": {"name": api}}
            for api in ("shared_office365", "shared_excelonlinebusiness")}
    return {"name": p["name"], "description": note(p, "Open the flow and pick your Outlook and Excel connections."),
            "clientdata": {"properties": {"connectionReferences": refs, "definition": definition},
                           "schemaVersion": "1.0.0.0"}}


def logic_app(p: dict) -> dict:
    """A Consumption logic app calling Microsoft Graph with its own managed identity (no secrets in it)."""
    mailbox = f"/users/{WARN}mailbox@your-company.com"
    msi = {"type": "ManagedServiceIdentity", "audience": "https://graph.microsoft.com"}

    def http(method: str, uri: str, body: dict | None = None, graph: bool = True) -> dict:
        inputs = {"method": method, "uri": uri}
        if graph:
            inputs["authentication"] = msi
        if body is not None:
            inputs["body"] = body
        return {"type": "Http", "inputs": inputs}

    actions: dict = {}
    inner: dict = {}
    item = "items('For_each_email')"
    if p["emails"]:
        _chain(actions, "Get_new_emails", http("GET", f"{GRAPH}{mailbox}/mailFolders/inbox/messages?$filter="
                                                      f"{urllib.parse.quote(NEW_EMAILS)}&$top=10"))
    if p["labels"]:
        _chain(inner, "Get_attachments", http("GET", f"{GRAPH}{mailbox}/messages/@{{{item}?['id']}}/attachments"))
        _chain(inner, "Read_the_PDF_fields", _pdf_compose(p, "Azure Document Intelligence (prebuilt invoice model)"))
    fields = "outputs('Read_the_PDF_fields')"
    if p["sheet"]:
        sheet = p["sheet"]
        _chain(inner, "Add_row", http("POST", _workbook_path(p, mailbox),
                                      {"values": [[_wdl_value(c, fields) for c in sheet["columns"]]]}))
    if p["web"]:
        web = p["web"]
        _chain(inner, f"Send_to_{_slug(web['site'])}", http(
            "POST", web["url"], {c["name"]: _wdl_value(c, fields) for c in web["fields"]}, graph=False))
    if p["move_to"]:
        _chain(inner, "Move_email", http("POST", f"{GRAPH}{mailbox}/messages/@{{{item}?['id']}}/move",
                                         {"destinationId": f"{WARN} id of the {p['move_to']} folder"}))
    if p["emails"]:
        _chain(actions, "For_each_email", {"type": "Foreach", "foreach": "@body('Get_new_emails')?['value']",
                                           "actions": inner})
    else:
        for name, action in inner.items():
            _chain(actions, name, action)
    return {"location": f"{WARN}westeurope", "identity": {"type": "SystemAssigned"},
            "tags": {"createdBy": "FlowSME"},
            "properties": {"state": "Disabled", "definition": {
                "$schema": "https://schema.management.azure.com/providers/Microsoft.Logic/schemas/2016-06-01/"
                           "workflowdefinition.json#", "contentVersion": "1.0.0.0", "parameters": {},
                "triggers": {"Every_15_minutes": {"type": "Recurrence",
                                                  "recurrence": {"frequency": "Minute", "interval": 15}}},
                "actions": actions}},
            "_readme": note(p, "Give the logic app's managed identity the Graph permissions Mail.ReadWrite and "
                               "Files.ReadWrite.All (application), and set the mailbox address.")}


def _az_token(resource: str) -> str:
    """A token from the Azure CLI's sign-in (az login), when no token was pasted."""
    az = shutil.which("az") or shutil.which("az.cmd")
    if not az:
        raise SystemExit("Paste an access token, or install the Azure CLI and run 'az login' once.")
    try:
        out = subprocess.run([az, "account", "get-access-token", "--resource", resource, "--query", "accessToken",
                              "-o", "tsv"], capture_output=True, text=True, timeout=60,
                             creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise SystemExit(f"The Azure CLI didn't answer: {exc}") from None
    if out.returncode != 0 or not out.stdout.strip():
        raise SystemExit(f"The Azure CLI has no token: run 'az login' first. {out.stderr.strip()[:200]}")
    return out.stdout.strip()


def _dataverse(v: dict) -> tuple[str, dict]:
    env = v["POWERAUTOMATE_ENV_URL"].strip().rstrip("/")
    if not env.startswith("https://"):
        env = "https://" + env
    token = v.get("POWERAUTOMATE_TOKEN", "").strip() or _az_token(env)
    return f"{env}/api/data/v9.2", {"Authorization": f"Bearer {token}", "OData-MaxVersion": "4.0",
                                    "OData-Version": "4.0", "Prefer": "return=representation"}


