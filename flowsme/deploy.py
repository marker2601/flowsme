def _make_http(mid: int, name: str, method: str, url: str, body: dict | None = None, graph: bool = True) -> dict:
    headers = [{"name": "Authorization", "value": f"Bearer {WARN} Microsoft Graph token"}] if graph else []
    mapper = {"url": url, "serializeUrl": False, "method": method, "headers": headers, "qs": [],
              "bodyType": "raw" if body is not None else "", "parseResponse": True, "authUser": "", "authPass": "",
              "timeout": "", "shareCookies": False, "ca": "", "rejectUnauthorized": True, "followRedirect": True,
              "useQuerystring": False, "gzip": True, "useMtls": False, "contentType": "application/json",
              "data": json.dumps(body, ensure_ascii=False, indent=1) if body is not None else "",
              "followAllRedirects": False}
    return {"id": mid, "module": "http:ActionSendData", "version": 3,
            "parameters": {"handleErrors": False, "useNewZLibDeCompress": True}, "mapper": mapper,
            "metadata": {"designer": {"x": 300 * (mid - 1), "y": 0, "name": name}}}


def make_blueprint(p: dict) -> dict:
    flow, mid = [], 0

    def nxt() -> int:
        nonlocal mid
        mid += 1
        return mid

    email_ref = fields_ref = None
    if p["emails"]:
        get = nxt()
        flow.append(_make_http(get, "Get new emails (Graph)", "get",
                               f"{GRAPH}/me/mailFolders/inbox/messages?$filter={urllib.parse.quote(NEW_EMAILS)}"
                               "&$top=10"))
        it = nxt()
        flow.append({"id": it, "module": "builtin:BasicFeeder", "version": 1, "parameters": {},
                     "mapper": {"array": f"{{{{{get}.data.value}}}}"},
                     "metadata": {"designer": {"x": 300 * (it - 1), "y": 0, "name": "One bundle per email"}}})
        email_ref = it
    if p["labels"]:
        att = nxt()
        flow.append(_make_http(att, "Get attachments (Graph)", "get",
                               f"{GRAPH}/me/messages/{{{{{email_ref}.id}}}}/attachments"))
        pick = nxt()
        flow.append(_make_http(pick, f"{WARN} Read the PDF fields", "post", f"https://{WARN}pdf-to-fields-service",
                               {"pdfBase64": f"{{{{first({att}.data.value).contentBytes}}}}", "labels": p["labels"]},
                               graph=False))
        fields_ref = pick

    def value(c: dict) -> str:
        if "pdf" in c and fields_ref:
            return f"{{{{{fields_ref}.data.`{c['pdf']}`}}}}" + (f" {WARN}" if "warn" in c else "")
        return f"{WARN} {c['warn']}"

    if p["sheet"]:
        sheet = p["sheet"]
        flow.append(_make_http(nxt(), f"Add row to {sheet['workbook']} (Graph)", "post", _workbook_path(p),
                               {"values": [[value(c) for c in sheet["columns"]]]}))
    if p["web"]:
        web = p["web"]
        flow.append(_make_http(nxt(), f"Send to {web['site']} API", "post", web["url"],
                               {c["name"]: value(c) for c in web["fields"]}, graph=False))
    if p["move_to"]:
        flow.append(_make_http(nxt(), f"Move email to {p['move_to']} (Graph)", "post",
                               f"{GRAPH}/me/messages/{{{{{email_ref}.id}}}}/move",
                               {"destinationId": f"{WARN} id of the {p['move_to']} folder"}))
    return {"name": p["name"], "flow": flow,
            "metadata": {"version": 1, "scenario": {"roundtrips": 1, "maxErrors": 3, "autoCommit": True,
                                                    "autoCommitTriggerLast": True, "sequential": False,
                                                    "confidential": False, "dataloss": False, "dlq": False,
                                                    "freshVariables": False},
                         "designer": {"orphans": [], "notes": [{"id": 1, "text": note(
                             p, "Replace each 'Bearer ⚠' header with a Microsoft 365 connection (or an OAuth "
                                "HTTP module), and pick a PDF reader for the PDF step.")}]}}}


def make_render(p: dict) -> dict:
    return {"blueprint": make_blueprint(p), "scheduling": {"type": "indefinitely", "interval": 900}}


def _make(v: dict) -> tuple[str, dict]:
    zone = v["MAKE_ZONE"].strip().lower().removeprefix("https://").split(".")[0] or "eu1"
    return f"https://{zone}.make.com/api/v2", {"Authorization": f"Token {v['MAKE_API_TOKEN']}"}


def make_create(doc: dict, v: dict) -> str:
    base, headers = _make(v)
    team = v.get("MAKE_TEAM_ID", "").strip()
    if not team:  # the first team of the first organization the token can see
        orgs = _call("Make", "GET", f"{base}/organizations", headers).get("organizations") or []
        if not orgs:
            raise SystemExit("Make: this token sees no organization. Enter the team id.")
        teams = _call("Make", "GET", f"{base}/teams?organizationId={orgs[0]['id']}", headers).get("teams") or []
        if not teams:
            raise SystemExit("Make: no team found. Enter the team id.")
        team = str(teams[0]["id"])
    body = {"blueprint": json.dumps(doc["blueprint"], ensure_ascii=False), "teamId": int(team),
            "scheduling": json.dumps(doc["scheduling"])}
    scenario = _call("Make", "POST", f"{base}/scenarios?confirmed=true", headers, body).get("scenario") or {}
    return f"Created in Make (inactive) as scenario {scenario.get('id', '?')} in team {team}."


def make_check(v: dict) -> str:
    base, headers = _make(v)
    me = _call("Make", "GET", f"{base}/users/me", headers).get("authUser") or {}
    return f"Make answered: signed in as {me.get('name') or me.get('email') or 'you'}."


