def rendered(spec: dict, n8n_workflow: dict) -> dict[str, dict]:
    """Each tool's workflow as its API takes it (the client app sends these with connect.create)."""
    p = dict(plan(spec), _n8n=n8n_workflow)
    return {t.id: t.render(p) for t in TARGETS.values()}


def export_all(spec: dict, n8n_workflow: dict, out: Path) -> dict[str, Path]:
    """Every platform's file, next to n8n_workflow.json (written by build.py)."""
    p = dict(plan(spec), _n8n=n8n_workflow)
    files = {}
    for t in TARGETS.values():
        if t.id == "n8n":
            continue
        path = out / t.file
        doc = t.render(p)
        path.write_text(json.dumps(t.export(doc) if t.export else doc, indent=2, ensure_ascii=False),
                        encoding="utf-8")
        files[f"{t.name} file"] = path
    return files


def values(target: Target) -> dict:
    """The target's settings from the user's environment (where the app's Build dialog saves them)."""
    from .app import saved_key

    v = {s.env: saved_key(s.env) or os.environ.get(s.env, "") for s in target.settings}
    missing = [s.label for s in target.settings if not s.optional and not v[s.env] and not s.default]
    if missing:
        names = ", ".join(f"{s.label} ({s.env})" for s in target.settings
                          if not s.optional and not v[s.env] and not s.default)
        raise SystemExit(f"{target.name}: enter {names} first, in the app's Build automation > Create it in, "
                         "or as environment variables for the command line.")
    for s in target.settings:
        v[s.env] = v[s.env] or s.default
    return v


def create(target_id: str, spec: dict, n8n_workflow: dict, settings: dict | None = None) -> str:
    target = TARGETS[target_id]
    p = dict(plan(spec), _n8n=n8n_workflow)
    v = settings if settings is not None else values(target)
    return connect_create(target_id, target.render(p), v, p["slug"])
