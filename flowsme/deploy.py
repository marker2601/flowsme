PICK_FIELDS_JS = r"""// Each label is looked for as '<label>: value' on one line. Check the patterns on a few real PDFs.
function pickFields(text, labels) {
  const fields = {};
  for (const label of labels) {
    const escaped = label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const match = text.match(new RegExp(escaped + '\\s*[:#]?\\s*(.+)', 'i'));
    fields[label] = match ? match[1].trim() : null;
  }
  return fields;
}
"""


def _js_value(c: dict, var: str = "fields") -> str:
    if "pdf" in c:
        value = f"{var}[{json.dumps(c['pdf'])}] ?? \"\""
        return value if "warn" not in c else f"{value} /* {WARN} {c['warn']} */"
    return f"\"\" /* {WARN} {c['warn']} */"


