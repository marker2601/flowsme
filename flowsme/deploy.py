# ---- the plan every platform follows -----------------------------------------------------------------

def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_") or "automation"


def plan(spec: dict) -> dict:
    """The automation as plain steps, from the build spec (the same facts n8n_workflow.json is built from)."""
    def column(f: dict) -> dict:
        c = {"name": f["field"]}
        if f["from_pdf"]:
            c["pdf"] = f["source"]["field"]
        if not (f["from_pdf"] and f["status"].startswith("recorded")):
            c["warn"] = f"{f['field']}: {f['status']}".replace("*/", "* /")
        return c

    sheet, web = spec["sheet"], spec["web"]
    emails = bool(spec["trigger_email"])
    return {
        "name": f"FlowSME: {spec['name']}", "slug": _slug(spec["name"])[:40].strip("_"), "emails": emails,
        "labels": spec["pdf_fields"] if emails else [],
        "sheet": {"workbook": sheet["document"] or "workbook.xlsx", "columns": [column(f) for f in sheet["fields"]]}
        if sheet else None,
        "web": {"site": web["site"], "url": f"https://{WARN}portal-api-url/{_slug(web['document'] or 'records')}",
                "fields": [column(f) for f in web["fields"]]} if web else None,
        "move_to": spec["move_to_folder"] if emails else None,
        "questions": [q.replace("**", "") for q in spec["open_questions"]],
    }


def note(p: dict, connect: str) -> str:
    lines = [f"{p['name']}", "Generated by FlowSME from a recording. Nothing here has run yet.", "",
             "Before the first run:", f"1. {connect}", f"2. Replace every {WARN} value (file path, table name, "
             "folder id, portal address).", "3. Run it once by hand with a test email and check each step's output.",
             "", "Open questions from the recording:"]
    lines += [f"- {q}" for q in p["questions"]] or ["- none"]
    return "\n".join(lines)


def _workbook_path(p: dict, base: str = "/me") -> str:
    book = urllib.parse.quote(p["sheet"]["workbook"])
    return f"{GRAPH}{base}/drive/root:/{WARN}folder/{book}:/workbook/tables/{WARN}Table1/rows/add"


