def _ts_module(mid: str, summary: str, code: str, inputs: dict) -> dict:
    transforms = {name: {"type": "javascript", "expr": expr} for name, expr in inputs.items()}
    return {"id": mid, "summary": summary,
            "value": {"type": "rawscript", "language": "bun", "content": code, "input_transforms": transforms}}


WINDMILL_GRAPH = """const GRAPH = "https://graph.microsoft.com/v1.0";

async function graph(token: string, method: string, url: string, body?: unknown) {
  const res = await fetch(url.startsWith("http") ? url : GRAPH + url, {
    method, headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  if (!res.ok) throw new Error(`${method} ${url}: ${res.status} ${await res.text()}`);
  return res.status === 204 ? null : res.json();
}
"""


