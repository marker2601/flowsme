def nodered_flow(p: dict) -> dict:
    """One flow tab: timer, then function nodes that prepare each Microsoft Graph call and http request nodes."""
    nodes: list[dict] = []
    auth = ('msg.headers = { Authorization: "Bearer " + env.get("GRAPH_TOKEN"), '
            '"Content-Type": "application/json" };\n')

    def add(node: dict) -> None:
        n = len(nodes)
        node.update(id=uuid.uuid4().hex[:16], x=150 + 230 * (n % 6), y=120 + 90 * (n // 6), wires=[])
        if nodes:
            nodes[-1]["wires"] = [[node["id"]]]
        nodes.append(node)

    def function(name: str, code: str, libs: list | None = None) -> None:
        add({"type": "function", "name": name, "func": code, "outputs": 1, "timeout": 0, "noerr": 0,
             "initialize": "", "finalize": "", "libs": libs or []})

    def http(name: str) -> None:
        add({"type": "http request", "name": name, "method": "use", "ret": "obj", "paytoqs": "ignore", "url": "",
             "tls": "", "persist": False, "proxy": "", "insecureHTTPParser": False, "authType": "",
             "senderr": False, "headers": []})

    add({"type": "inject", "name": "Every 15 minutes", "props": [{"p": "payload"}], "repeat": "900",
         "crontab": "", "once": False, "onceDelay": 0.1, "topic": "", "payload": "", "payloadType": "date"})
    if p["emails"]:
        function("Ask for new emails", auth + 'msg.method = "GET";\n'
                 f'msg.url = "{GRAPH}/me/mailFolders/inbox/messages?$filter=" + '
                 f'encodeURIComponent({json.dumps(NEW_EMAILS)}) + "&$top=10";\nreturn msg;')
        http("Get new emails (Graph)")
        function("One message per email", "// Graph returns { value: [messages] }: send one message per email\n"
                 "return [(msg.payload.value || []).map(m => ({\n"
                 "  email: { id: m.id, subject: m.subject, from: m.from?.emailAddress?.address },\n}))];")
    if p["labels"]:
        function("Ask for attachments", auth + f'msg.method = "GET";\nmsg.url = "{GRAPH}/me/messages/" + '
                 'msg.email.id + "/attachments";\nreturn msg;')
        http("Get attachments (Graph)")
        function("Read PDF fields", PICK_FIELDS_JS +
                 f"\nconst labels = {json.dumps(p['labels'])};\n"
                 "const pdf = (msg.payload.value || []).find(a => (a.name || '').toLowerCase().endsWith('.pdf'));\n"
                 "if (!pdf) return null; // no PDF in this email: skip it\n"
                 "const bytes = Buffer.from(pdf.contentBytes, 'base64');\n"
                 "const text = typeof pdfParse === 'function'\n"
                 "  ? (await pdfParse(bytes)).text                                // pdf-parse 1.x\n"
                 "  : (await new pdfParse.PDFParse({ data: bytes }).getText()).text; // pdf-parse 2.x\n"
                 "msg.fields = pickFields(text, labels);\nmsg.fileName = pdf.name;\nreturn msg;",
                 libs=[{"var": "pdfParse", "module": "pdf-parse"}])
    if p["sheet"]:
        sheet = p["sheet"]
        values = ",\n  ".join(_js_value(c) for c in sheet["columns"])
        function(f"Row for {sheet['workbook']}", "const fields = msg.fields || {};\n" + auth +
                 f'msg.method = "POST";\nmsg.url = {json.dumps(_workbook_path(p))};\n'
                 f"// Column order: {', '.join(c['name'] for c in sheet['columns'])}\n"
                 f"msg.payload = {{ values: [[\n  {values}\n]] }};\nreturn msg;")
        http(f"Add row to {sheet['workbook']} (Graph)")
    if p["web"]:
        web = p["web"]
        body = ",\n  ".join(f"{json.dumps(c['name'])}: {_js_value(c)}" for c in web["fields"])
        function(f"Request for {web['site']}", "const fields = msg.fields || {};\n"
                 f"const url = {json.dumps(web['url'])};\n"
                 f"if (url.includes('{WARN}')) {{ node.warn('Fill in the {web['site']} API address first'); "
                 "return null; }\n"
                 'msg.method = "POST";\nmsg.url = url;\nmsg.headers = { "Content-Type": "application/json" };\n'
                 f"// {WARN} Field names copied from the form; the real API may name them differently.\n"
                 f"msg.payload = {{\n  {body}\n}};\nreturn msg;")
        http(f"Send to {web['site']} API")
    if p["move_to"]:
        function(f"Move email to {p['move_to']}", auth + 'msg.method = "POST";\n'
                 f'msg.url = "{GRAPH}/me/messages/" + msg.email.id + "/move";\n'
                 f'msg.payload = {{ destinationId: "{WARN} id of the {p["move_to"]} folder" }};\nreturn msg;')
        http("Move email (Graph)")
    add({"type": "debug", "name": "Done", "active": True, "tosidebar": True, "console": False,
         "tostatus": False, "complete": "true", "targetType": "full"})
    nodes.insert(0, {"id": uuid.uuid4().hex[:16], "type": "comment", "name": "Read me first",
                     "info": note(p, "Set GRAPH_TOKEN (a Microsoft Graph access token) in this tab's environment "
                                     "variables, or add an OAuth2 node in front of each Graph call."),
                     "x": 150, "y": 50, "wires": []})
    return {"label": p["name"], "info": note(p, "Set GRAPH_TOKEN in this tab's environment variables."),
            "env": [{"name": "GRAPH_TOKEN", "value": "", "type": "str"}], "disabled": True,
            "nodes": nodes, "configs": []}


def nodered_export(doc: dict) -> list[dict]:
    """The editor's Import format: a tab node, then its nodes."""
    tab = {"id": uuid.uuid4().hex[:16], "type": "tab", **{k: doc[k] for k in ("label", "info", "env", "disabled")}}
    return [tab] + [dict(n, z=tab["id"]) for n in doc["nodes"]]


